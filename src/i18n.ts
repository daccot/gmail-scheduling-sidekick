const dict: Record<ResolvedLanguage, Dict> = { ja, en };

export function resolveLanguage(setting: LanguageSetting): ResolvedLanguage {
  if (setting === "ja" || setting === "en") return setting;
  return (navigator.language || "en").toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function tr(lang: ResolvedLanguage, key: string): string {
  return dict[lang][key] || dict.en[key] || key;
}

export function applyStaticI18n(lang: ResolvedLanguage): void {
  document.documentElement.lang = lang;
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = tr(lang, el.dataset.i18n || "");
  });
}